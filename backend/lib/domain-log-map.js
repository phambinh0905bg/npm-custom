import fs from "node:fs";

/**
 * Builds the nginx `map` that gives every domain of a host its own access log
 * file, and the helpers to write it to disk.
 *
 * Why a map and not `$host` directly: an access_log path may contain variables,
 * and in that case nginx opens the file named by whatever the variable holds.
 * `$host` comes from the request's Host header, so a request with
 * `Host: ../../etc/passwd` would choose the path. A map turns the header into a
 * value from a fixed list - only the domains written here can ever be part of a
 * file name, and anything else matches `default`.
 *
 * The same rules are used here and in the templates, so a map is only ever built
 * from values nginx cannot mistake for config syntax.
 */

// Safe as a map key and as a file name: no quotes, whitespace, braces, slashes or
// newlines. A single leading "*." is allowed for a wildcard proxy host.
const PLAIN_DOMAIN = /^(?:\*\.)?[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/i;

export const isPlainDomainName = (value) => typeof value === "string" && PLAIN_DOMAIN.test(value);

/**
 * The log file name for a domain. A wildcard becomes "wildcard.example.com" - a
 * literal "*" in a file name is legal but makes log rotation and shell globbing
 * unpleasant.
 *
 * @param   {String} domain
 * @returns {String}
 */
export const domainLogFileName = (domain) => domain.toLowerCase().replace(/^\*\./, "wildcard.");

// host_type as used by internalNginx.getFileFriendlyHostType() -> variable prefix
export const LOG_MAP_HOST_TYPES = {
	proxy_host: "proxy",
	redirection_host: "redirect",
	dead_host: "dead",
};

/**
 * @param   {String} hostType  proxy_host | redirection_host | dead_host
 * @param   {Number} hostId
 * @returns {String} the nginx variable name holding this host's log file name
 */
export const logMapVariable = (hostType, hostId) => {
	const prefix = LOG_MAP_HOST_TYPES[hostType];
	if (!prefix) {
		throw new Error(`No domain log map for host type ${hostType}`);
	}
	return `npm_domain_log_${prefix}_${hostId}`;
};

/**
 * @param   {String} hostType
 * @param   {Number} hostId
 * @returns {String} absolute path of the generated map file
 */
export const logMapFilePath = (dir, hostType, hostId) => `${dir}/${hostType}-${hostId}.conf`;

/**
 * @param   {String}   hostType
 * @param   {Number}   hostId
 * @param   {String[]} domains
 * @returns {String} the file contents, ready to write
 */
export const buildLogMapContent = (hostType, hostId, domains) => {
	const variable = logMapVariable(hostType, hostId);
	const label = hostType.replace(/_/g, " ");

	const lines = [
		"# Generated by Nginx Proxy Manager - do not edit, this file is rewritten.",
		`# Turns the Host header of ${label} #${hostId} into a log file name.`,
		"# Only the domains below can be selected; anything else falls back to",
		'# "unknown", so a spoofed Host cannot choose a path on disk.',
		`map $host $${variable} {`,
		// Lets a wildcard proxy host ("*.example.com") match its subdomains.
		"  hostnames;",
		'  default "unknown";',
	];

	for (const domain of domains || []) {
		if (isPlainDomainName(domain)) {
			lines.push(`  "${domain.toLowerCase()}" "${domainLogFileName(domain)}";`);
		}
	}

	lines.push("}", "");
	return lines.join("\n");
};

/**
 * Writes a host's map file, leaving it untouched when the content is unchanged
 * (so a no-op save does not touch the mtime or force an extra reload).
 *
 * @param   {String}   dir
 * @param   {String}   hostType
 * @param   {Number}   hostId
 * @param   {String[]} domains
 * @returns {Boolean} whether the file was written
 */
export const writeLogMap = (dir, hostType, hostId, domains) => {
	const filePath = logMapFilePath(dir, hostType, hostId);
	const content = buildLogMapContent(hostType, hostId, domains);

	if (fs.existsSync(filePath) && fs.readFileSync(filePath, { encoding: "utf8" }) === content) {
		return false;
	}

	fs.mkdirSync(dir, { recursive: true });
	fs.writeFileSync(filePath, content, { encoding: "utf8" });
	return true;
};

/**
 * Removes a host's map file.
 *
 * @param   {String} dir
 * @param   {String} hostType
 * @param   {Number} hostId
 */
export const removeLogMap = (dir, hostType, hostId) => {
	const filePath = logMapFilePath(dir, hostType, hostId);
	if (fs.existsSync(filePath)) {
		fs.rmSync(filePath, { force: true });
	}
};
